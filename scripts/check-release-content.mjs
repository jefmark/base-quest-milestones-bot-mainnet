import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const dist = process.argv[2] || '';
const source = (name) => fs.readFileSync(path.join(root, name), 'utf8');
const oldX = ['https://x.com/', 'BaseQuest', 'Milestones'].join('');
const newX = 'https://x.com/BaseQuestGame';
const botSite = 'https://botchain.ai';
const botScan = 'https://scan.botchain.ai';
const pages = ['about','community','contact','dashboard','home','nfts','rules','xp'];

for (const relative of ['src/main.js', ...pages.map(name => `public/pages/${name}.html`)]) {
  const html = source(relative);
  assert.ok(html.includes(botSite), `${relative}: missing official BOT Chain link`);
  assert.ok(html.includes(botScan), `${relative}: missing official BOT explorer link`);
  assert.ok(html.includes('BOT Chain'), `${relative}: missing BOT Chain attribution`);
  assert.ok(!html.includes(oldX), `${relative}: outdated X URL`);
  for (const url of [botSite, botScan]) {
    assert.ok(html.includes(`href="${url}"`), `${relative}: ${url} is not a clickable link`);
  }
}
for (const name of ['src/main.js', 'public/pages/community.html', 'public/pages/contact.html']) {
  assert.ok(source(name).includes(`href="${newX}"`), `${name}: X URL not updated`);
}
for (const name of pages) {
  const html = source(`public/pages/${name}.html`);
  assert.ok(html.includes('class="page-drawer"'), `${name}: navigation drawer changed`);
}
assert.ok(source('src/main.js').includes('v244-drawer'), 'Play navigation drawer changed');
for (const file of ['ci.yml', 'deploy-pages.yml', 'security.yml']) {
  const name = `.github/workflows/${file}`;
  assert.ok(fs.statSync(path.join(root, name)).size > 100, `${name}: missing workflow`);
  assert.match(source(name), /^on:/m, `${name}: no GitHub event trigger`);
  assert.match(source(name), /runs-on: ubuntu-latest/, `${name}: no runner`);
}
for (const entry of fs.readdirSync(root, { recursive: true, withFileTypes: true })) {
  if (!entry.isFile()) continue;
  const absolute = path.join(entry.parentPath || entry.path, entry.name);
  const relative = path.relative(root, absolute).replaceAll(path.sep, "/");
  if (relative.startsWith("node_modules/") || relative.startsWith("dist/") || relative.startsWith(".git/") || relative.startsWith("cache/") || relative.startsWith("artifacts/")) continue;
  if (/\.(png|webp|jpg|jpeg|gif|ico|zip|lock)$/i.test(entry.name)) continue;
  if (!(relative.startsWith("src/") || relative.startsWith("public/") || relative === "index.html")) continue;
  const value = fs.readFileSync(absolute, 'utf8');
  assert.ok(!/[\u0600-\u06ff]/u.test(value), `Non-English (Arabic/Persian script) in ${path.relative(root, absolute)}`);
  if (!/check-release-content\.mjs$/.test(absolute)) {
    assert.ok(!value.includes(oldX), `Outdated X URL in ${path.relative(root, absolute)}`);
  }
}
if (dist) {
  assert.ok(fs.existsSync(path.join(root, dist, 'index.html')), `${dist}/index.html missing`);
  // The Play page is generated by Vite inside JS assets, while the eight
  // independent pages are copied to dist/pages as standalone HTML.
  const assetsDirectory = path.join(root, dist, 'assets');
  const jsAssets = fs.readdirSync(assetsDirectory).filter(name => name.endsWith('.js'));
  assert.ok(jsAssets.length > 0, 'Vite JS assets missing');
  const scripts = jsAssets.map(name => fs.readFileSync(path.join(assetsDirectory, name), 'utf8')).join('\n');
  for (const required of [botSite, botScan, newX]) {
    assert.ok(scripts.includes(required), `Built Play bundle missing ${required}`);
  }
  for (const name of pages.map(n => `pages/${n}.html`)) {
    const html = fs.readFileSync(path.join(root, dist, name), 'utf8');
    assert.ok(html.includes(botSite) && html.includes(botScan), `${dist}/${name}: missing BOT links`);
    assert.ok(html.includes('class="page-drawer"'), `${dist}/${name}: missing navigation drawer`);
  }
  assert.ok(fs.readFileSync(path.join(root, dist, 'pages/community.html'), 'utf8').includes(newX));
}

console.log(`Release content verified: 9 site pages, BOT links, X link, English-only, 3 GitHub workflows${dist ? ', production HTML' : ''}.`);
